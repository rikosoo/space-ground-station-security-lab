#!/usr/bin/env python3
"""Turn the experiment JSON into LaTeX the paper can include.

Numbers in the paper are never typed by hand. This script reads
``research/results/*.json`` and emits macro definitions and table bodies under
``research/paper/generated/``. Re-running the experiments and rebuilding the
paper therefore cannot leave a stale figure in the text.
"""

from __future__ import annotations

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
RESULTS = ROOT / "research" / "results"
OUT = ROOT / "research" / "paper" / "generated"

RULE_NAMES = {
    "R01": "Brute force then success", "R02": "Unprofiled origin",
    "R03": "RBAC violation", "R04": "Unusual critical cmd",
    "R05": "Uplink auth failure", "R06": "Frame integrity cluster",
    "R07": "Physics violation", "R08": "Replayed frame",
    "R09": "Archive enumeration", "R10": "Archive volume anomaly",
    "R11": "Control-plane change",
}
ABLATION_LABELS = {
    "full": "Full stack", "no_mfa": "No MFA", "no_rbac": "No RBAC",
    "no_sdls_auth": "No frame authentication",
    "no_anti_replay": "No anti-replay window", "no_rate_limit": "No rate limit",
    "no_pass_window": "No pass-window check",
    "no_auto_response": "No automated containment",
    "no_block_expiry": "Blocks never expire", "none": "No controls",
}


def esc(text: str) -> str:
    return text.replace("&", r"\&").replace("_", r"\_").replace("%", r"\%")


def write_rows(path: pathlib.Path, rows: list) -> None:
    """Write the body rows of one table.

    These files are read with the TeX primitive (``\\inputrows`` in the paper's
    preamble), not with LaTeX's ``\\input``: the latter injects a ``\\par`` at end
    of file, which inside a tabular arrives before the last row is closed and
    makes the following ``\\bottomrule`` report a misplaced ``\\noalign``.
    """
    path.write_text("\n".join(rows).rstrip() + "\n")


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    base = json.loads((RESULTS / "baseline.json").read_text())
    macros = [
        "% Generated by research/experiments/make_macros.py -- do not edit.",
        rf"\newcommand{{\ResTrials}}{{{base['n_trials']}}}",
        rf"\newcommand{{\ResWarmupDays}}{{{base['config']['warmup_days']:.0f}}}",
        rf"\newcommand{{\ResMeasureDays}}{{{base['config']['measure_days']:.0f}}}",
        rf"\newcommand{{\ResEventsPerWindow}}{{{base['events_per_trial']:,.0f}}}",
        rf"\newcommand{{\ResFPDay}}{{{base['false_positives_per_day']['mean']:.2f}}}",
        rf"\newcommand{{\ResFPDayCI}}{{{base['false_positives_per_day']['ci95']:.2f}}}",
        rf"\newcommand{{\ResPrecision}}{{{base['precision']['mean'] * 100:.1f}}}",
        rf"\newcommand{{\ResFPWeek}}"
        rf"{{{base['false_positives_per_day']['mean'] * 7:.1f}}}",
        rf"\newcommand{{\BlockTTLHours}}"
        rf"{{{base['config']['block_ttl_s'] / 3600:.0f}}}",
    ]
    # LaTeX command names cannot contain digits, so A1..A5 become Aone..Afive.
    words = {"1": "one", "2": "two", "3": "three", "4": "four", "5": "five"}
    ttds = []
    for aid, a in base["attacks"].items():
        tag = "A" + words[aid[1]]
        ttds.append(a["ttd_mean_s"])
        macros += [
            rf"\newcommand{{\ResTTD{tag}}}{{{a['ttd_mean_s']:.1f}}}",
            rf"\newcommand{{\ResTTC{tag}}}{{{a['ttc_mean_s']:.1f}}}",
            rf"\newcommand{{\ResDet{tag}}}{{{a['detection_rate'] * 100:.0f}}}",
            rf"\newcommand{{\ResTTDMedian{tag}}}{{{a['ttd_median_s']:.1f}}}",
            rf"\newcommand{{\ResTTDPNinetyFive{tag}}}{{{a['ttd_p95_s']:.1f}}}",
            rf"\newcommand{{\ResTTDMax{tag}}}{{{a['ttd_max_s']:.1f}}}",
            rf"\newcommand{{\ResCI{tag}}}{{{a['ttd_ci95_s']:.1f}}}",
        ]
        # How often each rule was the first to fire. An attack whose modal rule
        # covers every trial has one detection path; one whose does not has
        # several, with a latency scale per path.
        freq = a["first_rule_freq"]
        modal = max(freq, key=lambda k: freq[k])
        macros += [
            rf"\newcommand{{\ResFirstRule{tag}}}{{{modal}}}",
            rf"\newcommand{{\ResFirstRuleTrials{tag}}}{{{freq[modal]}}}",
            rf"\newcommand{{\ResFallbackTrials{tag}}}"
            rf"{{{sum(v for k, v in freq.items() if k != modal)}}}",
        ]
        fallback = sorted((k for k in freq if k != modal),
                          key=lambda k: -freq[k])
        macros.append(rf"\newcommand{{\ResFallbackRule{tag}}}"
                      rf"{{{fallback[0] if fallback else '--'}}}")
    macros.append(rf"\newcommand{{\ResTTDMean}}{{{sum(ttds) / len(ttds):.1f}}}")
    macros.append(rf"\newcommand{{\ResTTDStream}}{{{min(ttds):.1f}}}")

    # ---- baseline table -----------------------------------------------------
    rows = []
    for aid, a in base["attacks"].items():
        first = ", ".join(sorted(a["first_rule_freq"], key=lambda k: -a["first_rule_freq"][k]))
        rows.append(
            f"{aid} & {a['detection_rate'] * 100:.0f} & {a['ttd_mean_s']:.1f} "
            f"& $\\pm${a['ttd_ci95_s']:.1f} & {a['ttd_median_s']:.1f} "
            f"& {a['ttd_p95_s']:.1f} "
            f"& {a['ttc_mean_s']:.1f} & {first} "
            f"& {a['mean_malicious_successes']:.1f} \\\\")
    write_rows(OUT / "tab-baseline.tex", rows)

    rows = []
    for rid in sorted(set(RULE_NAMES) | set(base["rules"])):
        st = base["rules"].get(rid, {"tp": 0, "fp": 0, "precision": float("nan"),
                                     "fp_per_day": 0.0})
        prec = "--" if st["tp"] + st["fp"] == 0 else f"{st['precision'] * 100:.0f}"
        rows.append(f"{rid} & {esc(RULE_NAMES.get(rid, '--'))} & {st['tp']} & {st['fp']} "
                    f"& {prec} & {st['fp_per_day']:.2f} \\\\")
    write_rows(OUT / "tab-rules.tex", rows)

    # ---- ablation -----------------------------------------------------------
    abl = json.loads((RESULTS / "ablation.json").read_text())
    rows = []
    for label, cfg in abl["configurations"].items():
        rows.append(
            f"{esc(ABLATION_LABELS.get(label, label))} & {cfg['detection_rate'] * 100:.0f} "
            f"& {cfg['mean_ttd_s']:.1f} & {cfg['total_malicious_successes']:.1f} "
            f"& {cfg['critical_commands_executed']:.1f} & {cfg['mb_exfiltrated']:,.0f} "
            f"& {cfg['fp_per_day']:.2f} \\\\")
    write_rows(OUT / "tab-ablation.tex", rows)
    full = abl["configurations"]["full"]
    macros += [
        rf"\newcommand{{\AblFullCrit}}{{{full['critical_commands_executed']:.1f}}}",
        rf"\newcommand{{\AblNoSDLSCrit}}"
        rf"{{{abl['configurations']['no_sdls_auth']['critical_commands_executed']:.1f}}}",
        rf"\newcommand{{\AblNoReplayCrit}}"
        rf"{{{abl['configurations']['no_anti_replay']['critical_commands_executed']:.1f}}}",
        rf"\newcommand{{\AblNoneCrit}}"
        rf"{{{abl['configurations']['none']['critical_commands_executed']:.1f}}}",
        rf"\newcommand{{\AblNoneMB}}"
        rf"{{{abl['configurations']['none']['mb_exfiltrated']:,.0f}}}",
        rf"\newcommand{{\AblNoResponseMB}}"
        rf"{{{abl['configurations']['no_auto_response']['mb_exfiltrated']:,.0f}}}",
        rf"\newcommand{{\AblFullMB}}{{{full['mb_exfiltrated']:,.0f}}}",
        rf"\newcommand{{\AblFullSucc}}{{{full['total_malicious_successes']:.1f}}}",
        rf"\newcommand{{\AblNoResponseSucc}}"
        rf"{{{abl['configurations']['no_auto_response']['total_malicious_successes']:.1f}}}",
        rf"\newcommand{{\AblFullFP}}{{{full['fp_per_day']:.2f}}}",
        rf"\newcommand{{\AblNoExpiryFP}}"
        rf"{{{abl['configurations']['no_block_expiry']['fp_per_day']:.2f}}}",
        rf"\newcommand{{\AblNoExpirySucc}}"
        rf"{{{abl['configurations']['no_block_expiry']['total_malicious_successes']:.1f}}}",
    ]

    # ---- sweeps -------------------------------------------------------------
    sweep = json.loads((RESULTS / "sweep.json").read_text())
    for param, rows_in in sweep["sweeps"].items():
        rows = [f"{r['value']} & {r['mean_ttd_s']:.1f} & {r['detection_rate'] * 100:.0f} "
                f"& {r['fp_per_day']:.2f} & {r['precision'] * 100:.0f} \\\\"
                for r in rows_in]
        write_rows(OUT / f"tab-sweep-{param.replace('_', '-')}.tex", rows)
    integ = {r["value"]: r for r in sweep["sweeps"]["integrity_threshold"]}
    macros += [
        rf"\newcommand{{\SweepIntegOneFP}}{{{integ[1]['fp_per_day']:.2f}}}",
        rf"\newcommand{{\SweepIntegOneTTD}}{{{integ[1]['mean_ttd_s']:.1f}}}",
        rf"\newcommand{{\SweepIntegThreeFP}}{{{integ[3]['fp_per_day']:.2f}}}",
        rf"\newcommand{{\SweepIntegThreeTTD}}{{{integ[3]['mean_ttd_s']:.1f}}}",
    ]
    batch = {r["value"]: r for r in sweep["sweeps"]["batch_latency_s"]}
    macros += [
        rf"\newcommand{{\SweepBatchFastTTD}}{{{batch[30.0]['mean_ttd_s']:.1f}}}",
        rf"\newcommand{{\SweepBatchSlowTTD}}{{{batch[900.0]['mean_ttd_s']:.1f}}}",
    ]

    # ---- cost ---------------------------------------------------------------
    cost = json.loads((RESULTS / "cost.json").read_text())
    lines = sorted(cost["lines"], key=lambda ln: -ln["monthly_usd"])
    rows = [f"{esc(ln['service'])} & {esc(ln['driver'])} & {ln['monthly_usd']:,.2f} \\\\"
            for ln in lines if ln["monthly_usd"] >= 0.01]
    rows.append(r"\midrule")
    rows.append(f"\\textbf{{Total}} & & \\textbf{{{cost['total_monthly_usd']:,.2f}}} \\\\")
    write_rows(OUT / "tab-cost.tex", rows)
    macros += [
        rf"\newcommand{{\CostMonthly}}{{{cost['total_monthly_usd']:,.0f}}}",
        rf"\newcommand{{\CostTopService}}{{{esc(lines[0]['service'])}}}",
        rf"\newcommand{{\CostTopShare}}"
        rf"{{{lines[0]['monthly_usd'] / cost['total_monthly_usd'] * 100:.0f}}}",
    ]
    scaling = [ln for ln in cost["scaling"].splitlines() if ln.startswith("| ")][2:]
    rows = []
    for ln in scaling:
        cells = [c.strip() for c in ln.strip("|").split("|")]
        rows.append(" & ".join(cells) + r" \\")
    write_rows(OUT / "tab-cost-scaling.tex", rows)
    per_hundred = scaling[-1].strip("|").split("|")[-1].strip()
    macros.append(rf"\newcommand{{\CostPerHundred}}{{{per_hundred}}}")

    (OUT / "results.tex").write_text("\n".join(macros) + "\n")
    print(f"wrote {len(list(OUT.glob('*.tex')))} files to research/paper/generated/")


if __name__ == "__main__":
    main()
